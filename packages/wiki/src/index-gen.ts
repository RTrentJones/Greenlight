import type { Wiki, WikiPage } from './load';
import { PAGE_TYPES } from './schema';

/**
 * The generated index and the log format (vision 08 §4). One line per non-archived page, grouped
 * under `## <type>`:
 *
 *   - [<title>](<path>) — <problem> · <root cause> · <fix>     (pattern)
 *   - [<title>](<path>) — <summary>                            (every other type)
 *
 * Clauses come from the page body, so the index never says anything the page does not. Sharding by
 * cell (LR-09) is not implemented yet.
 */

export interface IndexEntry {
  /** Wiki-relative link target, `./` stripped. */
  target: string;
  line: string;
}

const ENTRY_RE = /^\s*[-*] \[[^\]]*\]\(([^)\s]+)\)/;

/** The page entries of an index, in order. Headings and prose lines are not entries. */
export function parseIndex(text: string): IndexEntry[] {
  const out: IndexEntry[] = [];
  for (const line of text.split('\n')) {
    const m = ENTRY_RE.exec(line);
    if (m?.[1]) out.push({ target: m[1].replace(/^\.\//, ''), line: line.trimEnd() });
  }
  return out;
}

/** The pages the index must list: every parsed, non-archived page, in type then path order. */
export function indexedPages(wiki: Wiki): WikiPage[] {
  const order = (p: WikiPage) => PAGE_TYPES.indexOf(p.frontmatter.type);
  return [...wiki.pages.values()]
    .filter((p) => !p.archived)
    .sort((a, b) => order(a) - order(b) || a.path.localeCompare(b.path));
}

const HEADER =
  '# Index\n\n<!-- the page set is generated by `greenlight wiki lint --fix`; summaries may be reworded -->\n';

/** Generates the full index of `wiki` (03 §3 `generateIndex`). */
export function generateIndex(wiki: Wiki): string {
  return renderIndex(indexedPages(wiki), (p) => entryLine(p));
}

function renderIndex(pages: WikiPage[], line: (p: WikiPage) => string): string {
  const sections: string[] = [HEADER];
  for (const type of PAGE_TYPES) {
    const ofType = pages.filter((p) => p.frontmatter.type === type);
    if (ofType.length > 0) sections.push(`## ${type}\n\n${ofType.map(line).join('\n')}\n`);
  }
  return sections.join('\n');
}

function entryLine(page: WikiPage): string {
  const fm = page.frontmatter;
  const clauses =
    fm.type === 'pattern'
      ? ['Symptom', 'Root cause', 'Fix / workaround'].map((h) =>
          firstSentence(section(page.body, h)),
        )
      : [firstSentence(leadParagraph(page.body))];
  const summary = clauses.filter((c) => c !== '').join(' · ') || fm.title;
  return `- [${fm.title}](${page.path}) — ${summary}`;
}

/** The text under `## <heading>` up to the next heading of level ≤ 2. */
function section(body: string, heading: string): string {
  const lines = body.split('\n');
  const start = lines.findIndex((l) => l.trim() === `## ${heading}`);
  if (start < 0) return '';
  const rest = lines.slice(start + 1);
  const end = rest.findIndex((l) => /^#{1,2} /.test(l));
  return (end < 0 ? rest : rest.slice(0, end)).join('\n');
}

/** The first paragraph of prose, skipping headings, tables, comments and fenced code. */
function leadParagraph(body: string): string {
  const out: string[] = [];
  let fenced = false;
  for (const line of body.split('\n')) {
    if (line.startsWith('```')) fenced = !fenced;
    const prose = !fenced && !/^(#|\||<!--|```)/.test(line.trim());
    if (prose && line.trim() !== '') out.push(line);
    else if (out.length > 0) break;
  }
  return out.join('\n');
}

/** The first sentence of a paragraph, on one line, without a trailing period. */
function firstSentence(text: string): string {
  const para = text.trim().split(/\n\s*\n/)[0] ?? '';
  const flat = para.replace(/\s+/g, ' ').trim();
  const end = flat.search(/[.!?](\s|$)/);
  return (end < 0 ? flat : flat.slice(0, end)).trim();
}

/** Which link targets one index has that the other lacks. */
export function diffIndex(
  submitted: string,
  generated: string,
): { missing: string[]; extra: string[] } {
  const have = new Set(parseIndex(submitted).map((e) => e.target));
  const want = new Set(parseIndex(generated).map((e) => e.target));
  return {
    missing: [...want].filter((t) => !have.has(t)),
    extra: [...have].filter((t) => !want.has(t)),
  };
}

/**
 * Merges a maintainer's submitted index with the generated one (06 §2.3): the generated set and
 * grouping win, but a submitted line is kept for a page both list, because the maintainer writes
 * better summaries than a generator. Returns the merged index and each correction made.
 */
export function reconcileIndex(
  submitted: string,
  wiki: Wiki,
): { index: string; corrections: string[] } {
  const generated = generateIndex(wiki);
  const wording = new Map(parseIndex(submitted).map((e) => [e.target, e.line]));
  const { missing, extra } = diffIndex(submitted, generated);
  const index = renderIndex(indexedPages(wiki), (p) => wording.get(p.path) ?? entryLine(p));
  const corrections = [
    ...missing.map((t) => `added ${t}`),
    ...extra.map((t) => `dropped ${t} (no such page)`),
  ];
  return { index, corrections };
}

/** Appends one `## <ts> — <actor> — <operation>` entry to log.md's text (08 §4). */
export function appendLogEntry(
  log: string | undefined,
  entry: { ts: string; actor: string; operation: string; body: string },
): string {
  const prefix = log === undefined || log === '' ? '# Log\n' : log.replace(/\n*$/, '\n');
  return `${prefix}\n## ${entry.ts} — ${entry.actor} — ${entry.operation}\n${entry.body.trim()}\n`;
}
